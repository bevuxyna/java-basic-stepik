// Вася работает программистом и получает 50 долл. США за каждые 100 строк кода (за последние строки, которые не дотягивают до сотни,
// он не получает ничего). Т.е. за 99 строк он получит 0, за 199  строк получит 50, и т.д.
// За каждое третье опоздание Васю штрафуют на 20 долл. США.
// Программа должна реализовать три варианта расчетов:
// 1) Пользователь вводит желаемый доход Васи и количество опозданий. Подсчитать, сколько строк кода (минимально) ему нужно написать,чтобы получить сумму не менее желаемого.
// 2) Пользователь вводит количество строк кода, написанное Васей, и желаемый объем зарплаты. Подсчитать сколько раз Вася может опоздать (максимально).
// Если даже без опозданий желаемую  зарплату он не получит, вывести "ERROR".
// 3) Пользователь вводит количество строк кода и количество опозданий. Определить, сколько заплатят Васе. Если не заплатят вообще, то вывести 0.
// Сначала пользователь вводит номер варианта расчета, а потом два числа в соответствии с условием варианта (все числа целые).

// Например: 1 1000 4 означает первый вариант расчета, 1000 - желаемый доход, 4 - количество опозданий.
// Ответом должно быть минимальное количество строк кода, которое нужно написать.

// Если первое число, которое вводит пользователь, не равно 1, 2 или 3 (вариант расчета), то вывести "ERROR".

import java.util.Scanner;

class Task_2_2_4 {
    public static void main(String[] args) {
        Scanner scan = new Scanner(System.in);

        int variant = scan.nextInt();
        int var1 = scan.nextInt();
        int var2 = scan.nextInt();

        switch (variant) {
            case 1: {
                // var1 = желаемый доход, var2 = количество опозданий
                int want = var1;
                int late = var2;
                int fine = (late / 3) * 20;
                int need = want + fine;
                int blocks;

                if (need <= 0) {
                    blocks = 0;
                } else {
                    blocks = (need + 49) / 50;
                }
                System.out.println(blocks * 100);
                break;
            }
            case 2: {
                // var1 = количество строк, var2 = желаемая зарплата
                int lines = var1;
                int want = var2;
                int base = (lines / 100) * 50;

                if (base < want) {
                    System.out.println("ERROR");
                } else {
                    int maxFines = (base - want) / 20;
                    int maxLate = maxFines * 3 + 2;
                    System.out.println(maxLate);
                }
                break;
            }
            case 3: {
                // var1 = количество строк, var2 = количество опозданий
                int lines = var1;
                int late = var2;
                int salary = (lines / 100) * 50 - (late / 3) * 20;

                if (salary < 0) {
                    salary = 0;
                }
                System.out.println(salary);
                break;
            }
            default:
                System.out.println("ERROR");
        }
    }
}